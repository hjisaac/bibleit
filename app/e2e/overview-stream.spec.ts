import { test, expect } from '@playwright/test';
import { TELEMETRY_HEADERS } from '@bibleit/engine';

test.describe('AI Scripture Overview Streaming', () => {
  test.beforeEach(async ({ page }) => {
    await page.addInitScript(() => {
      localStorage.clear();
      sessionStorage.clear();
      localStorage.setItem('bibleit_active_tab', 'search');
    });
  });

  test('streams AI overview response and renders provider metadata', async ({ page }) => {
    // Intercept search request to return scripture passages
    await page.route('**/api/v1/search*', async (route) => {
      await route.fulfill({
        status: 200,
        contentType: 'application/json',
        body: JSON.stringify({
          query: 'What is love?',
          passages: [
            {
              chunk: {
                id: 1,
                book: '1JN',
                start: [4, 8],
                end: [4, 8],
                text: 'He who doesn’t love doesn’t know God, for God is love.',
              },
              score: 0.98,
              source: 'semantic',
            },
          ],
          parsedRefs: [],
        }),
      });
    });

    // Intercept generation request with hyphenated PascalCase headers and streamed answer
    await page.route('**/api/v1/generate*', async (route) => {
      await route.fulfill({
        status: 200,
        headers: {
          'Content-Type': 'text/plain; charset=utf-8',
          [TELEMETRY_HEADERS.PROVIDER]: 'gemini',
          [TELEMETRY_HEADERS.MODEL]: 'gemini-3.5-flash-lite',
          [TELEMETRY_HEADERS.ATTEMPTS]: '1',
          'Access-Control-Allow-Origin': '*',
          'Access-Control-Expose-Headers': Object.values(TELEMETRY_HEADERS).join(', '),
        },
        body: 'God is love [1 JOHN 4:8].',
      });
    });

    await page.goto('/');

    const searchInput = page.getByRole('textbox');
    await expect(searchInput).toBeVisible();

    // Submit topical query
    await searchInput.fill('What is love?');
    await searchInput.press('Enter');

    // Overview card must render with streamed content
    await expect(page.getByText('God is love [1 JOHN 4:8].')).toBeVisible({ timeout: 15000 });

    // Model attribution footer must be rendered
    await expect(page.getByText('Generated by gemini-3.5-flash-lite')).toBeVisible();
  });
});
